// Explicit, read-only management surfaces backed by the production tenant API.
// Every visible field is declared here so the shared page never falls back to a
// raw JSON inspector and never manufactures presentation data.

const field = (key, label, format = 'text', options = {}) =>
  Object.freeze({ key, label, format, ...options });

const tab = (id, label, path, columns, detail = columns, options = {}) =>
  Object.freeze({
    id,
    label,
    path,
    columns: Object.freeze(columns),
    detail: Object.freeze(detail),
    pageSize: 25,
    searchParam: 'search',
    rowKey: 'id',
    ...options,
  });

const related = (id, label, path, columns, options = {}) =>
  Object.freeze({
    id,
    label,
    path,
    columns: Object.freeze(columns),
    rowKey: 'id',
    ...options,
    summaryFields: options.summaryFields
      ? Object.freeze(options.summaryFields)
      : undefined,
  });

